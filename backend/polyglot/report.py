from __future__ import annotations

from polyglot.models import MigrationRequest, Plan, RunReport


def pr_body(req: MigrationRequest, plan: Plan, r: RunReport) -> str:
    def t(s):
        return "n/a" if s is None else f"{s.passed} passed, {s.failed} failed, {s.errors} errors"

    rows = "\n".join(f"| {s.title} | {s.status} | {len(s.files_changed)} |" for s in r.steps)
    flagged = [s for s in r.steps if s.status != "done"]
    todo = "\n".join(f"- **{s.title}**: {'; '.join(s.notes) or 'needs manual migration'}" for s in flagged) or "- none"
    sigs = "\n".join(
        f"| `{s.source_sig}` | `{s.target_sig}` | {s.target_file} |" for s in r.signatures[:40]
    ) or "| — | — | — |"
    return f"""## {req.instruction}

{plan.summary}

| Step | Status | Rust files |
|---|---|---|
{rows}

### Signature map
| C/C++ | Rust | Module |
|---|---|---|
{sigs}

**C tests before:** {t(r.tests_before)}
**Rust tests after:** {t(r.tests_after)}
**Repair iterations:** {r.repair_iterations}
**Unsafe mentions:** {r.unsafe_blocks}
**LLM calls:** {r.llm_calls} ({r.calls_by_tier}) — **Wall time:** {r.wall_seconds:.0f}s
**Tokens:** {r.prompt_tokens + r.completion_tokens}

### Needs human review
{todo}

_Generated by PolyGlot Refactor AI on Nebius Token Factory (NVIDIA Nemotron Ultra / Super / Nano)._
Every step is a separate commit so it can be reverted independently.
"""
